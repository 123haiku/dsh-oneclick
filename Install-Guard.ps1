#Requires -Version 5.1
<#
.SYNOPSIS
    Arms Guard.ps1 so the patch set survives DSH updates; removes it again with -Unregister.

.DESCRIPTION
    Guard.ps1 is only useful if something runs it. Two arming modes, picked automatically:

      task      Task Scheduler job DSH-Purge-Guard: at logon (+30s), at startup (+30s), and
                every -IntervalMinutes. Needs an elevated shell to register.
      startup   %APPDATA%\...\Startup\dsh-purge-guard.vbs -> hidden powershell Guard.ps1 -Watch.
                Per-user, no elevation, no admin prompt. This is what a normal account gets.

    Both end up running the same loop, so behaviour after an update is identical: a pass
    every minute (watch) or every N minutes (task) detects resources\app.asar coming back and
    heals it.

.PARAMETER Mode
    Auto (default) registers the task when elevated, otherwise the startup launcher.
    Task / Startup force one of them.

.PARAMETER Unregister
    Remove the task and the startup launcher.

.EXAMPLE
    .\Install-Guard.ps1
    .\Install-Guard.ps1 -IntervalMinutes 2
    .\Install-Guard.ps1 -Unregister
#>
[CmdletBinding()]
param(
    [string]$TaskName = 'DSH-Purge-Guard',
    [int]$IntervalMinutes = 5,
    [string]$GuardScript,
    [ValidateSet('Auto', 'Task', 'Startup')]
    [string]$Mode = 'Auto',
    [switch]$Unregister,
    [switch]$NoStart
)

$ErrorActionPreference = 'Stop'

$here = if ($PSScriptRoot) { $PSScriptRoot } else { Split-Path $PSCommandPath -Parent }
if (-not $GuardScript) { $GuardScript = Join-Path $here 'Guard.ps1' }
$startupDir = [Environment]::GetFolderPath('Startup')
$launcher = Join-Path $startupDir 'dsh-purge-guard.vbs'

function Remove-Guard {
    $task = Get-ScheduledTask -TaskName $TaskName -ErrorAction SilentlyContinue
    if ($task) { Unregister-ScheduledTask -TaskName $TaskName -Confirm:$false; Write-Host "removed task '$TaskName'" }
    if (Test-Path $launcher) { Remove-Item $launcher -Force; Write-Host "removed launcher $launcher" }
    $pidFile = Join-Path (Join-Path $env:LOCALAPPDATA 'dsh-oneclick') 'guard.pid'
    if (Test-Path $pidFile) {
        $old = 0
        try { $old = [int](Get-Content $pidFile -Raw).Trim() } catch { }
        if ($old -gt 0) {
            $p = Get-Process -Id $old -ErrorAction SilentlyContinue
            if ($p) { Stop-Process -Id $old -Force; Write-Host "stopped watcher pid $old" }
        }
        Remove-Item $pidFile -Force -ErrorAction SilentlyContinue
    }
}

if ($Unregister) { Remove-Guard; exit 0 }

if (-not (Test-Path $GuardScript)) { throw "Guard.ps1 not found: $GuardScript" }

$identity = [Security.Principal.WindowsIdentity]::GetCurrent()
$elevated = (New-Object Security.Principal.WindowsPrincipal($identity)).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)

if ($Mode -eq 'Task' -and -not $elevated) {
    throw 'Mode Task needs an elevated shell; run Install-Guard.ps1 as administrator or use -Mode Startup'
}

$useTask = $Mode -eq 'Task' -or ($Mode -eq 'Auto' -and $elevated)

if ($useTask) {
    $action = New-ScheduledTaskAction -Execute 'powershell.exe' `
        -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$GuardScript`""

    $logon = New-ScheduledTaskTrigger -AtLogOn
    $logon.Delay = [TimeSpan]::FromSeconds(30)
    $logon.Repetition = (New-ScheduledTaskTrigger -Once -At (Get-Date).Date.AddMinutes(2) `
            -RepetitionInterval (New-TimeSpan -Minutes $IntervalMinutes) `
            -RepetitionDuration (New-TimeSpan -Days 3650)).Repetition

    $startup = New-ScheduledTaskTrigger -AtStartup
    $startup.Delay = [TimeSpan]::FromSeconds(30)

    $settings = New-ScheduledTaskSettingsSet -MultipleInstances IgnoreNew -StartWhenAvailable `
        -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries -ExecutionTimeLimit (New-TimeSpan -Minutes 10)

    $principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive

    Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger @($logon, $startup) `
        -Settings $settings -Principal $principal -Force `
        -Description 'Re-applies the dsh-purge patch set after a DeepSeek Harness update (Guard.ps1)' | Out-Null

    $t = Get-ScheduledTask -TaskName $TaskName
    "armed: task $($t.TaskName)  state=$($t.State)  every ${IntervalMinutes}m"
}
else {
    # The launcher must not point into a checkout that can move or be renamed. Keep a stable
    # copy under %LOCALAPPDATA% and run that; re-running this script refreshes it.
    $stableDir = Join-Path $env:LOCALAPPDATA 'dsh-oneclick'
    New-Item -ItemType Directory -Force $stableDir | Out-Null
    $stableGuard = Join-Path $stableDir 'Guard.ps1'
    Copy-Item $GuardScript $stableGuard -Force

    $vbs = @"
' dsh-purge guard launcher - generated by Install-Guard.ps1
' Start hidden, keep watching, one instance (Guard.ps1 holds a pid lock).
Set sh = CreateObject("WScript.Shell")
sh.Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File ""$stableGuard"" -Watch", 0, False
"@
    New-Item -ItemType Directory -Force $startupDir | Out-Null
    Set-Content -LiteralPath $launcher -Value $vbs -Encoding ASCII
    "armed: startup launcher $launcher"
    "        runs $stableGuard"
}

if (-not $NoStart) {
    if ($useTask) {
        Start-ScheduledTask -TaskName $TaskName
        Start-Sleep -Seconds 4
        $info = Get-ScheduledTaskInfo -TaskName $TaskName
        "started: lastResult=$($info.LastTaskResult) lastRun=$($info.LastRunTime) nextRun=$($info.NextRunTime)"
    }
    else {
        & wscript.exe $launcher
        Start-Sleep -Seconds 6
        $pidFile = Join-Path (Join-Path $env:LOCALAPPDATA 'dsh-oneclick') 'guard.pid'
        if (Test-Path $pidFile) { "started: watcher pid $((Get-Content $pidFile -Raw).Trim())" }
        else { 'started: launcher returned, no pid file yet (check guard.log)' }
    }
}

Write-Host ''
Write-Host 'first detect pass:' -ForegroundColor Cyan
& powershell.exe -NoProfile -ExecutionPolicy Bypass -File $GuardScript -Detect
Write-Host "detect exit: $LASTEXITCODE  (0 clean / 3 drift)"
